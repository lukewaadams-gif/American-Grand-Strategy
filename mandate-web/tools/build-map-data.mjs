// Build-time only: turns public-domain map data into drawing data for the interface (no map library at runtime).
//   us-atlas states-albers-10m (US Census cartographic boundaries, already projected Albers USA with Alaska and
//   Hawaii inset, 975 x 610) -> SVG paths, label points and small-state callouts.
// Writes src/main/ts/generated/usStates.ts.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const out = path.join(root, 'src/main/ts/generated');
fs.mkdirSync(out, { recursive: true });

const CODES = {
  'Alabama': 'AL', 'Alaska': 'AK', 'Arizona': 'AZ', 'Arkansas': 'AR', 'California': 'CA', 'Colorado': 'CO', 'Connecticut': 'CT',
  'Delaware': 'DE', 'District of Columbia': 'DC', 'Florida': 'FL', 'Georgia': 'GA', 'Hawaii': 'HI', 'Idaho': 'ID', 'Illinois': 'IL',
  'Indiana': 'IN', 'Iowa': 'IA', 'Kansas': 'KS', 'Kentucky': 'KY', 'Louisiana': 'LA', 'Maine': 'ME', 'Maryland': 'MD',
  'Massachusetts': 'MA', 'Michigan': 'MI', 'Minnesota': 'MN', 'Mississippi': 'MS', 'Missouri': 'MO', 'Montana': 'MT',
  'Nebraska': 'NE', 'Nevada': 'NV', 'New Hampshire': 'NH', 'New Jersey': 'NJ', 'New Mexico': 'NM', 'New York': 'NY',
  'North Carolina': 'NC', 'North Dakota': 'ND', 'Ohio': 'OH', 'Oklahoma': 'OK', 'Oregon': 'OR', 'Pennsylvania': 'PA',
  'Rhode Island': 'RI', 'South Carolina': 'SC', 'South Dakota': 'SD', 'Tennessee': 'TN', 'Texas': 'TX', 'Utah': 'UT',
  'Vermont': 'VT', 'Virginia': 'VA', 'Washington': 'WA', 'West Virginia': 'WV', 'Wisconsin': 'WI', 'Wyoming': 'WY',
};

/** TopoJSON: delta-encoded, quantized arcs; a ring is a list of arc indexes (~i = arc i reversed). */
function decode(topo) {
  const [sx, sy] = topo.transform.scale, [tx, ty] = topo.transform.translate;
  const arcs = topo.arcs.map(arc => {
    let x = 0, y = 0;
    return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; });
  });
  const ring = idx => {
    const pts = [];
    for (const i of idx) {
      const a = i >= 0 ? arcs[i] : arcs[~i].slice().reverse();
      a.forEach((p, k) => { if (k > 0 || pts.length === 0) pts.push(p); });
    }
    return pts;
  };
  const polygons = g => g.type === 'Polygon' ? [g.arcs.map(ring)] : g.type === 'MultiPolygon' ? g.arcs.map(p => p.map(ring)) : [];
  return { polygons };
}

const r1 = v => Math.round(v * 10) / 10;
function pathOf(polys) {
  let d = '';
  for (const poly of polys) for (const ring of poly) {
    let last = null;
    ring.forEach((p, i) => {
      const q = [r1(p[0]), r1(p[1])];
      if (last && q[0] === last[0] && q[1] === last[1]) return;
      d += (i === 0 ? 'M' : 'L') + q[0] + ' ' + q[1];
      last = q;
    });
    d += 'Z';
  }
  return d;
}
function area(ring) { let a = 0; for (let i = 0, n = ring.length; i < n; i++) { const [x0, y0] = ring[i], [x1, y1] = ring[(i + 1) % n]; a += x0 * y1 - x1 * y0; } return a / 2; }
function centroid(ring) {
  let a = 0, cx = 0, cy = 0;
  for (let i = 0, n = ring.length; i < n; i++) { const [x0, y0] = ring[i], [x1, y1] = ring[(i + 1) % n], f = x0 * y1 - x1 * y0; a += f; cx += (x0 + x1) * f; cy += (y0 + y1) * f; }
  return [cx / (3 * a), cy / (3 * a)];
}

const topo = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/us-atlas/states-albers-10m.json'), 'utf8'));
const { polygons } = decode(topo);
const states = [];
for (const g of topo.objects.states.geometries) {
  const name = g.properties.name, code = CODES[name];
  if (!code) continue;                                   // territories are not in the game
  const polys = polygons(g);
  let best = null, bestA = 0;
  for (const poly of polys) { const a = Math.abs(area(poly[0])); if (a > bestA) { bestA = a; best = poly[0]; } }
  let [x, y] = centroid(best);
  // a few states' area centroids sit badly for a label (Florida's panhandle, Michigan's two peninsulas, Louisiana)
  const nudge = { FL: [18, 22], MI: [6, 16], LA: [-10, 0], ID: [0, 22], CA: [-8, 10], KY: [6, 2], VA: [10, 4], WV: [-4, 6], OK: [10, 0], MN: [-6, 10] };
  if (nudge[code]) { x += nudge[code][0]; y += nudge[code][1]; }
  states.push({ code, name, fips: g.id, d: pathOf(polys), label: [r1(x), r1(y)], area: Math.round(bestA) });
}
// Small states in the north-east get a labelled callout box to the right of the map, as on a broadcast map.
const CALLOUTS = ['VT', 'NH', 'MA', 'RI', 'CT', 'NJ', 'DE', 'MD', 'DC'];
const callouts = CALLOUTS.map((code, i) => ({ code, box: [918, 150 + i * 30], anchor: states.find(s => s.code === code).label }));
const nation = pathOf(polygons(topo.objects.nation.geometries ? topo.objects.nation.geometries[0] : topo.objects.nation));

const ts = `// Generated by tools/build-map-data.mjs from us-atlas 3.0.1 (US Census cartographic boundaries; ISC licence).
// Do not edit: rebuild with \`npm run data\`.
export interface StateShape { code: string; name: string; fips: string; d: string; label: [number, number]; area: number; }
export interface Callout { code: string; box: [number, number]; anchor: [number, number]; }
export const VIEWBOX = { width: 975, height: 610 };
export const STATES: StateShape[] = ${JSON.stringify(states)};
export const CALLOUTS: Callout[] = ${JSON.stringify(callouts)};
export const NATION: string = ${JSON.stringify(nation)};
`;
fs.writeFileSync(path.join(out, 'usStates.ts'), ts);
console.log(`map data: ${states.length} states, ${(ts.length / 1024).toFixed(0)} KB -> src/main/ts/generated/usStates.ts`);
