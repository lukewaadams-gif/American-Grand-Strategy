/** TopoJSON: delta-encoded, quantized arcs; a ring is a list of arc indexes (~i = arc i reversed). */
function decode(topo) {
  const [sx, sy] = topo.transform.scale, [tx, ty] = topo.transform.translate;
  const arcs = topo.arcs.map(arc => {
    let x = 0, y = 0;
    return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; });
  });
  const ring = idx => {
    const pts = [];
    for (const i of idx) {
      const a = i >= 0 ? arcs[i] : arcs[~i].slice().reverse();
      a.forEach((p, k) => { if (k > 0 || pts.length === 0) pts.push(p); });
    }
    return pts;
  };
  const polygons = g => g.type === 'Polygon' ? [g.arcs.map(ring)] : g.type === 'MultiPolygon' ? g.arcs.map(p => p.map(ring)) : [];
  return { polygons };
}

const r1 = v => Math.round(v * 10) / 10;
function pathOf(polys) {
  let d = '';
  for (const poly of polys) for (const ring of poly) {
    let last = null;
    ring.forEach((p, i) => {
      const q = [r1(p[0]), r1(p[1])];
      if (last && q[0] === last[0] && q[1] === last[1]) return;
      d += (i === 0 ? 'M' : 'L') + q[0] + ' ' + q[1];
      last = q;
    });
    d += 'Z';
  }
  return d;
}
function area(ring) { let a = 0; for (let i = 0, n = ring.length; i < n; i++) { const [x0, y0] = ring[i], [x1, y1] = ring[(i + 1) % n]; a += x0 * y1 - x1 * y0; } return a / 2; }
function centroid(ring) {
  let a = 0, cx = 0, cy = 0;
  for (let i = 0, n = ring.length; i < n; i++) { const [x0, y0] = ring[i], [x1, y1] = ring[(i + 1) % n], f = x0 * y1 - x1 * y0; a += f; cx += (x0 + x1) * f; cy += (y0 + y1) * f; }
  return [cx / (3 * a), cy / (3 * a)];
}

const topo = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/us-atlas/states-albers-10m.json'), 'utf8'));
const { polygons } = decode(topo);
const states = [];
for (const g of topo.objects.states.geometries) {
  const name = g.properties.name, code = CODES[name];
  if (!code) continue;                                   // territories are not in the game
  const polys = polygons(g);
  let best = null, bestA = 0;
  for (const poly of polys) { const a = Math.abs(area(poly[0])); if (a > bestA) { bestA = a; best = poly[0]; } }
  let [x, y] = centroid(best);
  // a few states' area centroids sit badly for a label (Florida's panhandle, Michigan's two peninsulas, Louisiana)
  const nudge = { FL: [18, 22], MI: [6, 16], LA: [-10, 0], ID: [0, 22], CA: [-8, 10], KY: [6, 2], VA: [10, 4], WV: [-4, 6], OK: [10, 0], MN: [-6, 10] };
  if (nudge[code]) { x += nudge[code][0]; y += nudge[code][1]; }
  states.push({ code, name, fips: g.id, d: pathOf(polys), label: [r1(x), r1(y)], area: Math.round(bestA) });
}
// Small states in the north-east get a labelled callout box to the right of the map, as on a broadcast map.
const CALLOUTS = ['VT', 'NH', 'MA', 'RI', 'CT', 'NJ', 'DE', 'MD', 'DC'];
const callouts = CALLOUTS.map((code, i) => ({ code, box: [918, 150 + i * 30], anchor: states.find(s => s.code === code).label }));
const nation = pathOf(polygons(topo.objects.nation.geometries ? topo.objects.nation.geometries[0] : topo.objects.nation));

const ts = `// Generated by tools/build-map-data.mjs from us-atlas 3.0.1 (US Census cartographic boundaries; ISC licence).
// Do not edit: rebuild with \`npm run data\`.
export interface StateShape { code: string; name: string; fips: string; d: string; label: [number, number]; area: number; }
export interface Callout { code: string; box: [number, number]; anchor: [number, number]; }
export const VIEWBOX = { width: 975, height: 610 };
export const STATES: StateShape[] = ${JSON.stringify(states)};
export const CALLOUTS: Callout[] = ${JSON.stringify(callouts)};
export const NATION: string = ${JSON.stringify(nation)};
`;
fs.writeFileSync(path.join(out, 'usStates.ts'), ts);
console.log(`map data: ${states.length} states, ${(ts.length / 1024).toFixed(0)} KB -> src/main/ts/generated/usStates.ts`);

// ---- the world (the Situation Room, presidency milestone 8) ---------------------------------------------------------------
// world-atlas countries-110m (Natural Earth 1:110m; public domain) in the Robinson projection, 1000 units wide, cut at
// about 62 degrees south: the projection and frame Resolute Desk's world map uses, so its country label points fit.
const ROBINSON = [[1.0, 0.0], [0.9986, 0.062], [0.9954, 0.124], [0.99, 0.186], [0.9822, 0.248], [0.973, 0.31], [0.96, 0.372], [0.9427, 0.434],
  [0.9216, 0.4958], [0.8962, 0.5571], [0.8679, 0.6176], [0.835, 0.6769], [0.7986, 0.7346], [0.7597, 0.7903], [0.7186, 0.8435], [0.6732, 0.8936],
  [0.6213, 0.9394], [0.5722, 0.9761], [0.5322, 1.0]];
const R = 1000 / (2 * 0.8487 * Math.PI), TOP = 1.3523 * R, WORLD_H = 447;
function robinson(lon, lat) {
  const a = Math.min(90, Math.abs(lat)) / 5, i = Math.min(17, Math.floor(a)), f = a - i;
  const X = ROBINSON[i][0] + (ROBINSON[i + 1][0] - ROBINSON[i][0]) * f, Y = ROBINSON[i][1] + (ROBINSON[i + 1][1] - ROBINSON[i][1]) * f;
  return [500 + 0.8487 * R * X * lon * Math.PI / 180, TOP - Math.sign(lat) * 1.3523 * R * Y];
}
// ISO 3166-1 numeric ids of the game's forty countries and the United States
const ISO = { 156: 'CN', 643: 'RU', 804: 'UA', 826: 'GB', 250: 'FR', 276: 'DE', 380: 'IT', 124: 'CA', 484: 'MX', 392: 'JP', 410: 'KR', 408: 'KP', 158: 'TW',
  356: 'IN', 586: 'PK', 376: 'IL', 364: 'IR', 682: 'SA', 792: 'TR', 818: 'EG', 634: 'QA', 784: 'AE', 400: 'JO', 368: 'IQ', 760: 'SY', 76: 'BR', 32: 'AR',
  862: 'VE', 192: 'CU', 591: 'PA', 616: 'PL', 348: 'HU', 208: 'DK', 246: 'FI', 36: 'AU', 608: 'PH', 360: 'ID', 704: 'VN', 566: 'NG', 710: 'ZA', 840: 'US' };
const wtopo = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/world-atlas/countries-110m.json'), 'utf8'));
// decode without the US map's projection transform: world-atlas arcs are quantized longitude and latitude
const wdecode = (() => {
  const [sx, sy] = wtopo.transform.scale, [tx, ty] = wtopo.transform.translate;
  const arcs = wtopo.arcs.map(arc => { let x = 0, y = 0; return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; }); });
  const ring = idx => { const pts = []; for (const i of idx) { const a = i >= 0 ? arcs[i] : arcs[~i].slice().reverse(); a.forEach((p, k) => { if (k > 0 || pts.length === 0) pts.push(p); }); } return pts; };
  return g => g.type === 'Polygon' ? [g.arcs.map(ring)] : g.type === 'MultiPolygon' ? g.arcs.map(p => p.map(ring)) : [];
})();
const world = [];
for (const g of wtopo.objects.countries.geometries) {
  if (g.properties.name === 'Antarctica') continue;
  // a ring that crosses the date line (Fiji) is drawn east of it, off the frame's edge, not across the whole map
  const unwrap = ring => { const lons = ring.map(p => p[0]); return Math.max(...lons) - Math.min(...lons) > 270 ? ring.map(([lon, lat]) => [lon < 0 ? lon + 360 : lon, lat]) : ring; };
  const polys = wdecode(g).map(poly => poly.map(ring => unwrap(ring).map(([lon, lat]) => robinson(lon, Math.max(-62.5, lat)))));
  const d = pathOf(polys);
  if (!d) continue;
  world.push({ id: ISO[Number(g.id)] ?? '', name: g.properties.name, d });
}
const wts = `// Generated by tools/build-map-data.mjs from world-atlas 2.0.2 (Natural Earth 1:110m, public domain; ISC licence),
// in the Robinson projection, ${1000} x ${WORLD_H}. Do not edit: rebuild with \`npm run data\`.
export interface CountryShape { id: string; name: string; d: string; }
export const WORLD_VIEWBOX = { width: 1000, height: ${WORLD_H} };
export const WORLD: CountryShape[] = ${JSON.stringify(world)};
`;
fs.writeFileSync(path.join(out, 'world.ts'), wts);
console.log(`map data: ${world.length} countries, ${(wts.length / 1024).toFixed(0)} KB -> src/main/ts/generated/world.ts`);

// ---- the Gulf (the Strait of Hormuz crisis, docs/HORMUZ.md) -------------------------------------------------------------
// world-atlas countries-10m (Natural Earth 1:10m; public domain), so the strait's islands show, clipped to the Gulf from
// Kuwait to the Gulf of Oman (47-61.5 degrees east, 22.5-30.8 north) in an equirectangular projection true at 26.5 north,
// 1000 units wide. The crisis places its sites, minefields and ships by longitude and latitude with the same numbers.
const G = { lon0: 47, lon1: 61.5, lat0: 22.5, lat1: 30.8, cos: Math.cos(26.5 * Math.PI / 180) };
G.k = 1000 / ((G.lon1 - G.lon0) * G.cos);
const GULF_H = Math.round((G.lat1 - G.lat0) * G.k);
const gproj = ([lon, lat]) => [(lon - G.lon0) * G.cos * G.k, (G.lat1 - lat) * G.k];
const gtopo = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/world-atlas/countries-10m.json'), 'utf8'));
const gdecode = (() => {
  const [sx, sy] = gtopo.transform.scale, [tx, ty] = gtopo.transform.translate;
  const arcs = gtopo.arcs.map(arc => { let x = 0, y = 0; return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; }); });
  const ring = idx => { const pts = []; for (const i of idx) { const a = i >= 0 ? arcs[i] : arcs[~i].slice().reverse(); a.forEach((p, k) => { if (k > 0 || pts.length === 0) pts.push(p); }); } return pts; };
  return g => g.type === 'Polygon' ? [g.arcs.map(ring)] : g.type === 'MultiPolygon' ? g.arcs.map(p => p.map(ring)) : [];
})();
// Sutherland-Hodgman against the frame (a little beyond it, so no seam shows at the edges)
function clip(ring, x0, y0, x1, y1) {
  const edges = [[p => p[0] >= x0, (a, b) => [x0, a[1] + (b[1] - a[1]) * (x0 - a[0]) / (b[0] - a[0])]],
    [p => p[0] <= x1, (a, b) => [x1, a[1] + (b[1] - a[1]) * (x1 - a[0]) / (b[0] - a[0])]],
    [p => p[1] >= y0, (a, b) => [a[0] + (b[0] - a[0]) * (y0 - a[1]) / (b[1] - a[1]), y0]],
    [p => p[1] <= y1, (a, b) => [a[0] + (b[0] - a[0]) * (y1 - a[1]) / (b[1] - a[1]), y1]]];
  let out = ring;
  for (const [inside, cut] of edges) {
    const src = out; out = [];
    for (let i = 0; i < src.length; i++) {
      const cur = src[i], prev = src[(i + src.length - 1) % src.length];
      if (inside(cur)) { if (!inside(prev)) out.push(cut(prev, cur)); out.push(cur); } else if (inside(prev)) out.push(cut(prev, cur));
    }
    if (!out.length) break;
  }
  return out;
}
const thin = ring => { const o = []; for (const p of ring) { const q = o[o.length - 1]; if (!q || Math.hypot(p[0] - q[0], p[1] - q[1]) >= 1.1) o.push(p); } return o; };
const GULF_NAMES = { 364: 'Iran', 682: 'Saudi Arabia', 784: 'United Arab Emirates', 512: 'Oman', 634: 'Qatar', 48: 'Bahrain', 414: 'Kuwait', 368: 'Iraq', 586: 'Pakistan' };
const gulf = [];
for (const g of gtopo.objects.countries.geometries) {
  const polys = gdecode(g).map(poly => poly.map(ring => thin(clip(ring.map(gproj), -4, -4, 1004, GULF_H + 4))).filter(r => r.length >= 3)).filter(p => p.length);
  const d = pathOf(polys);
  if (!d) continue;
  gulf.push({ id: ISO[Number(g.id)] ?? String(g.id), name: GULF_NAMES[Number(g.id)] ?? g.properties.name, d });
}
const gts = `// Generated by tools/build-map-data.mjs from world-atlas 2.0.2 (Natural Earth 1:10m, public domain; ISC licence): the
// Gulf, ${G.lon0}-${G.lon1} E and ${G.lat0}-${G.lat1} N, equirectangular at 26.5 N, 1000 x ${GULF_H}. Do not edit: rebuild with \`npm run data\`.
export interface GulfShape { id: string; name: string; d: string; }
export const GULF_VIEWBOX = { width: 1000, height: ${GULF_H} };
export const GULF_PROJECTION = ${JSON.stringify({ lon0: G.lon0, lat1: G.lat1, cos: Math.round(G.cos * 1e6) / 1e6, k: Math.round(G.k * 1e4) / 1e4 })};
export const GULF: GulfShape[] = ${JSON.stringify(gulf)};
`;
fs.writeFileSync(path.join(out, 'gulf.ts'), gts);
console.log(`map data: ${gulf.length} countries on the Gulf map, ${(gts.length / 1024).toFixed(0)} KB -> src/main/ts/generated/gulf.ts`);
